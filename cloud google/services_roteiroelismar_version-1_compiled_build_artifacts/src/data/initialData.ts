// Generates initial visits based on clients scheduled for today's weekday
export const generateVisitsForDate = (dateStr: string, clients: Client[]): Visit[] => {
  const date = new Date(dateStr + 'T12:00:00'); // Prevent timezone offsets
  const weekday = getDayNameFromDate(date);
  
  // Find clients configured for this weekday
  const dailyClients = clients
    .filter(c => c.weekday === weekday)
    .sort((a, b) => a.routeOrder - b.routeOrder);

  return dailyClients.map((c, idx) => ({
    id: `v_${dateStr}_${c.id}`,
    clientId: c.id,
    clientName: c.name,
    address: c.address,
    date: dateStr,
    status: 'pending',
    isExtra: false
  }));
};
