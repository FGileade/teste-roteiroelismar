// Helper to determine weekday name
export const getDayNameFromDate = (date: Date): WeekDay => {
  const days: WeekDay[] = ['saturday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const dayIndex = date.getDay(); // 0 is Sunday, but let's default to Saturday for 0 and 6
  if (dayIndex === 0) return 'sunday' as any; // Not officially in our weekdays but useful
  return days[dayIndex];
};

